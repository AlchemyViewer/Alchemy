    /**
     * @class TestLLSDParsing
     * @brief Base class for of a parse tester.
     */
    template <class parser_t>
    class TestLLSDParsing
    {
    public:
        TestLLSDParsing()
        {
            mParser = new parser_t;
        }

        void require_parse(
            const std::string& what,
            const std::string& in,
            const LLSD& expected_value,
            S32 expected_count,
            S32 depth_limit = -1)
        {
            std::stringstream input;
            input.str(in);

            LLSD parsed_result;
            mParser->reset();   // reset() call is needed since test code re-uses mParser
            S32 parsed_count = mParser->parse(input, parsed_result, in.size(), depth_limit);
            INFO(what);
            REQUIRE_THAT(parsed_result, ll_test::LLSDEquals(expected_value));

            // This count check is really only useful for expected
            // parse failures, since the value check above already
            // requires equality.
            REQUIRE(parsed_count == expected_count);
        }

        LLPointer<parser_t> mParser;
    };


