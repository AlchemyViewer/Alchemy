ALPanelProfileLegacy::~ALPanelProfileLegacy()
{
    if (LLAvatarPropertiesProcessor::instanceExists() && ALPanelProfileLegacyTab::getAvatarId().notNull())
        LLAvatarPropertiesProcessor::getInstance()->removeObserver(ALPanelProfileLegacyTab::getAvatarId(), this);
    if (mAvatarNameCacheConnection.connected())
        mAvatarNameCacheConnection.disconnect();
    if (mNameChangedConnection.connected())
        mNameChangedConnection.disconnect();
    auto popup_menu = static_cast<LLMenuGL*>(mPopupMenuHandle.get());
    if (popup_menu)
    {
        popup_menu->die();
        mPopupMenuHandle.markDead();
    }
}

