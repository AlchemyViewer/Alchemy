ALPanelProfileLegacy::ChildStack::ChildStack()
:   mParent(nullptr)
{
}

ALPanelProfileLegacy::ChildStack::~ChildStack()
{
    while (!mStack.empty())
    {
        view_list_t& top = mStack.back();
        for (auto viewp : top)
        {
            if (viewp)
            {
                viewp->die();
            }
        }
        mStack.pop_back();
    }
}

void ALPanelProfileLegacy::ChildStack::setParent(LLPanel* parent)
{
    llassert_always(parent != nullptr);
    mParent = parent;
}

/// Save current parent's child views and remove them from the child list.
bool ALPanelProfileLegacy::ChildStack::push()
{
    view_list_t vlist = *mParent->getChildList();

    for (auto viewp : vlist)
    {
        mParent->removeChild(viewp);
    }

    mStack.push_back(vlist);
    dump();
    return true;
}

/// Restore saved children (adding them back to the child list).
bool ALPanelProfileLegacy::ChildStack::pop()
{
    if (mStack.empty())
    {
        LL_WARNS() << "Empty stack" << LL_ENDL;
        llassert(mStack.size() == 0);
        return false;
    }

    view_list_t& top = mStack.back();
    for (auto viewp : top)
    {
        mParent->addChild(viewp);
    }

    mStack.pop_back();
    dump();
    return true;
}

/// Temporarily add all saved children back.
void ALPanelProfileLegacy::ChildStack::preParentReshape()
{
    mSavedStack = mStack;
    while(!mStack.empty())
    {
        pop();
    }
}

/// Add the temporarily saved children back.
void ALPanelProfileLegacy::ChildStack::postParentReshape()
{
    mStack = mSavedStack;
    mSavedStack = stack_t();

    for (const auto& vlist : mStack)
    {
        for (auto viewp : vlist)
        {
            LL_DEBUGS() << "removing " << viewp->getName() << LL_ENDL;
            mParent->removeChild(viewp);
        }
    }
}

void ALPanelProfileLegacy::ChildStack::dump()
{
    unsigned lvl = 0;
    LL_DEBUGS() << "child stack dump:" << LL_ENDL;
    for (const auto& vlist : mStack)
    {
        ++lvl;
        std::ostringstream dbg_line;
        dbg_line << "lvl #" << lvl << ":";
        for (const auto& list_it : vlist)
        {
            dbg_line << " " << list_it->getName();
        }
        LL_DEBUGS() << dbg_line.str() << LL_ENDL;
    }
}
