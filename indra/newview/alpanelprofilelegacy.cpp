void ALPanelProfileLegacy::ALPanelProfilePicks::onPanelClassifiedSave(ALPanelClassifiedEdit* panel)
{
    if (!panel->canClose())
    {
        return;
    }

    if (panel->isNew())
    {
        mEditClassifiedPanels[panel->getClassifiedId()] = panel;

        ALClassifiedItem* c_item = new ALClassifiedItem(getAvatarId(), panel->getClassifiedId());
        c_item->fillIn(panel);

        LLSD c_value;
        c_value.insert(CLASSIFIED_ID, c_item->getClassifiedId());
        c_value.insert(CLASSIFIED_NAME, c_item->getClassifiedName());
        mClassifiedsList->addItem(c_item, c_value, ADD_TOP);

        //c_item->setDoubleClickCallback(boost::bind(&ALPanelProfilePicks::onDoubleClickClassifiedItem, this, _1));
        c_item->setRightMouseUpCallback(boost::bind(&ALPanelProfilePicks::onRightMouseUpItem, this, _1, _2, _3, _4));
        c_item->setMouseUpCallback(boost::bind(&ALPanelProfilePicks::updateButtons, this));
        c_item->childSetAction("info_chevron", boost::bind(&ALPanelProfilePicks::onClickInfo, this));

        // order does matter, showTab will invoke arrange for accordions.
        //mClassifiedsAccTab->changeOpenClose(false);
        //showTab("tab_classifieds", true);
    }
    else if (panel->isNewWithErrors())
    {
        ALClassifiedItem* c_item = dynamic_cast<ALClassifiedItem*>(mClassifiedsList->getSelectedItem());
        llassert(c_item);
        if (c_item)
        {
            c_item->fillIn(panel);
        }
    }
    else
    {
        onPanelClassifiedClose(panel);
        return;
    }

    onPanelPickClose(panel);
    updateButtons();
}

void ALPanelProfileLegacy::ALPanelProfilePicks::onPanelClassifiedClose(ALPanelClassifiedInfo* panel)
{
    if(panel->getInfoLoaded() && !panel->isDirty())
    {
        std::vector<LLSD> values;
        mClassifiedsList->getValues(values);
        for (auto& value : values)
        {
            LLUUID c_id = value[CLASSIFIED_ID].asUUID();
            if(panel->getClassifiedId() == c_id)
            {
                ALClassifiedItem* c_item = dynamic_cast<ALClassifiedItem*>(mClassifiedsList->getItemByValue(value));
                llassert(c_item);
                if (c_item)
                {
                    c_item->setClassifiedName(panel->getClassifiedName());
                    c_item->setDescription(panel->getDescription());
                    c_item->setSnapshotId(panel->getSnapshotId());
                }
            }
        }
    }

    onPanelPickClose(panel);
}

