static LLPanelInjector<ALPanelEventInfo> t_event_info("panel_al_event_info");

ALPanelEventInfo::ALPanelEventInfo()
:   LLPanel()
,   mEvent()
,   mEventID(0)
{
    mEventNotifierConnection = gEventNotifier.setEventInfoCallback(boost::bind(&ALPanelEventInfo::processEventReply, this, _1));
}

ALPanelEventInfo::~ALPanelEventInfo()
{
    if (mEventNotifierConnection.connected())
    {
        mEventNotifierConnection.disconnect();
    }
}

bool ALPanelEventInfo::postBuild()
{
    childSetAction("teleport_btn", boost::bind(&ALPanelEventInfo::onBtnTeleport, this));
    childSetAction("show_on_map_btn", boost::bind(&ALPanelEventInfo::onBtnMap, this));
    childSetAction("remind_btn", boost::bind(&ALPanelEventInfo::onBtnRemind, this));
    return LLPanel::postBuild();
}

void ALPanelEventInfo::onOpen(const LLSD& key)
{
    setEventID(key["event_id"].asInteger());

    gEventNotifier.add(getEventID());
}

// *TODO: localize this bitch.
std::string ALPanelEventInfo::formatFromMinutes(U32 time)
{
    U32 hours = time / 60;
    U32 minutes = time % 60;

    std::ostringstream output;
    if (hours)
        output << hours << " " << getString("hours") << " ";
    if (minutes)
        output << minutes << " " << getString("minutes");
    return output.str();
}

bool ALPanelEventInfo::processEventReply(const LLEventInfo& event)
{
    if (event.mID != getEventID()) return false; // no
    mEvent = event;
    getChild<LLUICtrl>("name")->setValue(mEvent.mName);
    getChild<LLUICtrl>("desc")->setValue(mEvent.mDesc);
    getChild<LLUICtrl>("duration")->setValue(formatFromMinutes(mEvent.mDuration));
    getChild<LLUICtrl>("host")->setValue(LLSLURL("agent", LLUUID(mEvent.mRunByID), "inspect").getSLURLString());
    getChild<LLUICtrl>("time")->setValue(mEvent.mTimeStr);
    // *TODO: Prettier
    //std::string time;
    //LLStringUtil::formatDatetime(time, "%a %d %b %Y %H:%M", "slt", mEvent.eventEpoch);
    //getChild<LLUICtrl>("time")->setValue(time);

    // *TODO: Add translation strings
    //getChild<LLUICtrl>("category")->setValue(LLTrans::getString(mEvent.category));
    getChild<LLUICtrl>("category")->setValue(mEvent.mCategoryStr);
    getChild<LLUICtrl>("cover")->setValue(mEvent.mHasCover
                                          ? LLResMgr::getInstance()->getMonetaryString(mEvent.mCover)
                                          : getString("free"));
    bool mature = (mEvent.mEventFlags & EVENT_FLAG_MATURE);
    getChild<LLUICtrl>("content_type")->setValue(getString(mature ? "type_mature" : "type_pg"));
    getChild<LLIconCtrl>("content_type_moderate")->setVisible(mature);
    getChild<LLIconCtrl>("content_type_general")->setVisible(!mature);
    getChild<LLUICtrl>("location")->setValue(LLSLURL(mEvent.mSimName, mEvent.mPosGlobal).getSLURLString());
    getChild<LLButton>("remind_btn")->setLabel(getString(gEventNotifier.hasNotification(mEvent.mID)
                                                         ? "no_reminder"
                                                         : "reminder"));
    return true;
}

void ALPanelEventInfo::onBtnTeleport()
{
    if (!mEvent.mPosGlobal.isExactlyZero())
    {
        gAgent.teleportViaLocation(mEvent.mPosGlobal);
        LLFloaterWorldMap* worldmap = LLFloaterWorldMap::getInstance();
        if (worldmap)
            worldmap->trackLocation(mEvent.mPosGlobal);
    }
}

void ALPanelEventInfo::onBtnMap()
{
    LLFloaterWorldMap* worldmap = LLFloaterWorldMap::getInstance();
    if (!mEvent.mPosGlobal.isExactlyZero() && worldmap)
    {
        worldmap->trackLocation(mEvent.mPosGlobal);
        LLFloaterReg::showInstance("world_map", "center");
    }
}

void ALPanelEventInfo::onBtnRemind()
{
    if (gEventNotifier.hasNotification(mEvent.mID))
    {
        gEventNotifier.remove(mEvent.mID);
        getChild<LLButton>("remind_btn")->setLabel(getString("reminder"));
    }
    else
    {
        gEventNotifier.add(mEvent.mID);
        getChild<LLButton>("remind_btn")->setLabel(getString("no_reminder"));
    }
}
